#!/bin/sh
# Host tests: the BLE service, glue and vendored od/core compiled for the host against the SDK
# headers, under gcc and (when installed) clang with ASan/UBSan. Then the panel bus the upload
# produced is compared with what od_epd_replay prints for the same packets.
#
#   host/tests/run.sh [preset key, default 0xE011]
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
OUT=$REPO/host/build
KEY=${1:-0xE011}
mkdir -p "$OUT"

sh "$REPO/host/equiv/build_capture.sh" "$OUT" >/dev/null

python3 - "$REPO/presets/drive_presets_nrf52811.json" "$KEY" "$OUT/preset_blob.h" <<'EOF'
import json, sys
d = json.load(open(sys.argv[1]))["panels"][sys.argv[2]]
b = bytes.fromhex(d["framed_hex"])
planes = d["modes"][0]["planes"]
bpp = 2 if d["color_scheme"] == 3 else 1
frame = (d["width"] * bpp + 7) // 8 * d["height"] * planes
idle = next(bytes.fromhex(p["body_hex"])[2] for p in d["packets"] if p["id"] == 0xB1)
with open(sys.argv[3], "w") as f:
    f.write("/* generated by host/tests/run.sh */\n")
    f.write(f"#define PRESET_IC {d['panel_ic_type']}u\n#define PRESET_W {d['width']}u\n")
    f.write(f"#define PRESET_H {d['height']}u\n#define PRESET_SCHEME {d['color_scheme']}u\n")
    f.write(f"#define PRESET_IDLE {idle}u\n#define PRESET_FRAME_BYTES {frame}u\n")
    f.write("static const uint8_t PRESET_FRAMED[] = {" + ",".join(str(x) for x in b) + "};\n")
EOF

FLAGS=$(cd "$REPO/build-nrf52" && make --no-print-directory \
        --eval='hostflags: ; @echo $(filter -D%,$(CFLAGS)) $(addprefix -I,$(INC_FOLDERS))' hostflags)
FLAGS=$(echo "$FLAGS" | sed -e "s|-I\.\./|-I$REPO/|g" -e "s|-I\.\. |-I$REPO |")
SRC="$HERE/test_service.c $HERE/fds_sim.c $REPO/EPD/EPD_service.c $REPO/glue/od_nrf_config.c
     $REPO/glue/od_nrf_display.c $REPO/glue/od_nrf_bootguard.c $REPO/qr/qrcode.c"
for m in od_epd od_epd_cfg od_cfg_index od_display od_color od_config_store od_config_tlv \
         od_config_asm od_advert od_cmd_spi_raw; do
  SRC="$SRC $REPO/od/core/$m.c"
done

build() { # cc extra-flags exe
  # shellcheck disable=SC2086
  $1 -std=gnu99 -O1 -g -w $2 -DSVCALL_AS_NORMAL_FUNCTION -DOD_BOOTGUARD_HOST_TEST \
     -I"$HERE/stubs" -I"$HERE" -I"$OUT" $FLAGS $SRC -o "$3"
}

build gcc "" "$OUT/test_service"
BUS_LOG=$OUT/bus.log "$OUT/test_service"
if command -v clang >/dev/null 2>&1; then
  build clang "-fsanitize=address,undefined -fno-omit-frame-pointer -fno-sanitize-recover=all" \
        "$OUT/test_service_asan"
  BUS_LOG=$OUT/bus_asan.log "$OUT/test_service_asan"
else
  echo "clang not installed: sanitizer run skipped"
fi

# The upload's panel bus against od_epd_replay for the same packets (mode 0, then sleep).
python3 - "$REPO/presets/drive_presets_nrf52811.json" "$KEY" "$OUT/bus.log" "$OUT/od_epd_replay" <<'EOF'
import json, subprocess, sys, tempfile
d = json.load(open(sys.argv[1]))["panels"][sys.argv[2]]
def norm(lines):
    out = []
    for ln in lines:
        t = ln.split()
        if not t: continue
        if t[0] == "C": out.append(["C", t[1], ""])
        elif t[0] == "D" and out and out[-1][0] == "C": out[-1][2] += t[1]
        elif t[0] == "I": out.append(["I"])
    # an image is the data of the command before the marker on the replay side; on the bus
    # side it is that command's long data
    res = []
    for o in out:
        if o[0] == "C" and len(o[2]) > 2 * 255:
            res += [("C", o[1], ""), ("I",)]
        elif o[0] == "I":
            if not res or res[-1] != ("I",): res.append(("I",))
        else:
            res.append(tuple(o))
    return res
bus = norm(open(sys.argv[3]).read().splitlines())
with tempfile.NamedTemporaryFile(suffix=".bin") as f:
    f.write(bytes.fromhex(d["framed_hex"])); f.flush()
    rep = []
    for mode in ("0", "sleep"):
        r = subprocess.run([sys.argv[4], f.name, mode, str(d["width"]), str(d["height"])],
                           capture_output=True, text=True, check=True)
        rep += r.stdout.splitlines()
rep = norm(rep)
ok = bus == rep
print(f"bus vs replay ({sys.argv[2]} {d['name']}): {'equal' if ok else 'DIFFERENT'} "
      f"({len(bus)} / {len(rep)} events)")
if not ok:
    for i, (a, b) in enumerate(zip(bus, rep)):
        if a != b:
            print("first difference at", i, a, b); break
    sys.exit(1)
EOF
